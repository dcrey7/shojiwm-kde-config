"""Build the two ShojiWM Global Themes (Plasma look-and-feel packages).

  org.shojiwm.mac.desktop   "ShojiWM Mac"   your panel with Kickoff, traffic lights
  org.shojiwm.aero.desktop  "ShojiWM Aero"  dark Aero glass: Seven-Black panel
                                            theme, SevenStart orb menu

Both rebuild the same panel and desktop from one saved Plasma config, so
switching keeps every widget and setting. Only the start button and the Plasma
theme differ. Run it once while your desktop looks the way you like it (or
pass a saved copy of the file):

    uv run python make-global-themes.py [path/to/plasma-org.kde.plasma.desktop-appletsrc]

SHOJI_START_ICON sets the Kickoff icon of the Mac look (an icon name or a
file path; default start-here-kde). The icon theme and widget style come from
your kdeglobals, so applying a look keeps them.
"""

import configparser
import json
import os
import pathlib
import re
import shutil
import sys

HOME = pathlib.Path.home()
# This folder (plasma-themes/ in the config repo).
SETUP = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SNAPSHOT = HOME / ".config/plasma-org.kde.plasma.desktop-appletsrc"
LNF_DIR = HOME / ".local/share/plasma/look-and-feel"
MAC_START_ICON = os.environ.get("SHOJI_START_ICON", "start-here-kde")
ORB_SHEET = SETUP / "assets/start-orb/start-orb-vista-sheet.png"
PANEL_THICKNESS = 40
# The start orb: the ball is about 1.15x the panel and sticks out above it,
# like Vista (40 px bar, 56 px orb picture, about a 46 px ball).
ORB_SIZE = 56
# The desktop widget positions, when the saved config has none for any screen.
SCREEN_KEY = "ItemGeometries-2560x1440"


def parse_kconfig(path: pathlib.Path) -> dict[tuple[str, ...], dict[str, str]]:
    """KConfig file -> {(group, subgroup, ...): {key: value}}."""
    groups: dict[tuple[str, ...], dict[str, str]] = {}
    current: tuple[str, ...] | None = None
    for line in path.read_text().splitlines():
        if line.startswith("["):
            current = tuple(re.findall(r"\[([^\]]*)\]", line))
            groups.setdefault(current, {})
        elif "=" in line and current is not None:
            key, value = line.split("=", 1)
            groups[current][key] = value
    return groups


def unescape(value: str) -> str:
    """Undo KConfig's escapes, so writeConfig stores the same text again."""
    return value.replace("\\\\", "\\").replace("\\s", " ")


def js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def applet_config_lines(var: str, groups, prefix: tuple[str, ...]) -> list[str]:
    """writeConfig calls for one applet's [Configuration] tree."""
    lines = []
    for group, entries in sorted(groups.items()):
        if group[: len(prefix)] != prefix or len(group) < len(prefix) + 1:
            continue
        rest = group[len(prefix):]
        if rest[0] != "Configuration" or "ConfigDialog" in rest:
            continue
        sub = list(rest[1:])
        if not entries:
            continue
        lines.append(f"{var}.currentConfigGroup = {js(sub)};")
        for key, value in entries.items():
            lines.append(f"{var}.writeConfig({js(key)}, {js(unescape(value))});")
    shortcut = groups.get(prefix + ("Shortcuts",), {}).get("global")
    if shortcut:
        lines.append(f"{var}.globalShortcut = {js(shortcut)};")
    return lines


def layout_script(groups, start_button: str) -> str:
    """The Plasma layout script: one bottom panel and the desktop widgets."""
    panels = [g for g, e in groups.items() if len(g) == 2 and g[0] == "Containments" and e.get("plugin") == "org.kde.panel"]
    desktops = [g for g, e in groups.items() if len(g) == 2 and g[0] == "Containments" and e.get("plugin") == "org.kde.desktopcontainment"]
    out = [
        "// Generated by shojiwm-setup/bin/make-global-themes.py. Do not edit by hand.",
        "// The panels are rebuilt from scratch, so drop any that survived.",
        "panels().forEach(function (p) { p.remove(); });",
    ]
    for p in panels:
        order = groups.get(p + ("General",), {}).get("AppletOrder", "").split(";")
        out += [
            "var panel = new Panel;",
            'panel.location = "bottom";',
            f"panel.height = {PANEL_THICKNESS};",
            "panel.floating = false;",
        ]
        for aid in [a for a in order if a]:
            prefix = p + ("Applets", aid)
            plugin = groups.get(prefix, {}).get("plugin")
            if not plugin:
                continue
            var = f"w{aid}"
            if plugin == "org.kde.plasma.kickoff":
                out += start_button_lines(var, groups, prefix, start_button)
                continue
            if plugin == "org.kde.plasma.trash":
                # Our trash button minimizes its open window on a second click
                # (plasmoids/org.shojiwm.trashtoggle); KDE's own cannot.
                out.append(f'var {var} = panel.addWidget("org.shojiwm.trashtoggle");')
                continue
            out.append(f"var {var} = panel.addWidget({js(plugin)});")
            out += applet_config_lines(var, groups, prefix)
            if plugin == "org.kde.plasma.icontasks":
                # No hover previews and no window highlighting, in both looks:
                # the previews stream the window and got stuck on screen, and
                # highlighting needs a KWin effect ShojiWM does not have.
                out += [
                    f'{var}.currentConfigGroup = ["General"];',
                    f'{var}.writeConfig("showToolTips", false);',
                    f'{var}.writeConfig("highlightWindows", false);',
                ]
            if plugin == "org.kde.plasma.icontasks" and start_button == "sevenstart":
                # Aero task buttons have 2-3 px margins (32 px icons); "Large"
                # spacing gives them back the Windows 7 width (~52 px).
                out += [f'{var}.currentConfigGroup = ["General"];', f'{var}.writeConfig("iconSpacing", 3);']
            if plugin == "cachyos.workspace-indicator":
                # Glass pills on Aero, the plain circles on Mac (see
                # patch-workspace-indicator.py).
                glass = "true" if start_button == "sevenstart" else "false"
                out += [f'{var}.currentConfigGroup = ["General"];', f'{var}.writeConfig("glass", {glass});']
            if plugin == "org.kde.plasma.systemtray":
                tray = groups.get(prefix + ("General",), {})
                out.append(f'var tray{aid} = desktopById({var}.readConfig("SystrayContainmentId"));')
                out.append(f"if (tray{aid}) {{")
                out.append(f'  tray{aid}.currentConfigGroup = ["General"];')
                for key in ("extraItems", "knownItems"):
                    if key in tray:
                        out.append(f"  tray{aid}.writeConfig({js(key)}, {js(tray[key].split(','))});")
                out.append("}")
    for d in desktops:
        entries = groups[d]
        wall = groups.get(d + ("Wallpaper", "org.kde.image", "General"), {}).get("Image")
        # Positions are saved per screen size; take the first one there is.
        key = next((k for k in entries if k.startswith("ItemGeometries-")), SCREEN_KEY)
        geometries = parse_geometries(entries.get(key, ""))
        out += [
            "desktopsForActivity(currentActivity()).forEach(function (desk) {",
            '  desk.wallpaperPlugin = "org.kde.image";',
        ]
        if wall:
            out += [
                '  desk.currentConfigGroup = ["Wallpaper", "org.kde.image", "General"];',
                f'  desk.writeConfig("Image", {js(wall)});',
            ]
        out += [
            "  // The widgets live on the first screen only; old ones go first.",
            "  if (desk.screen != 0) { return; }",
            "  desk.widgets().forEach(function (w) { w.remove(); });",
            '  desk.currentConfigGroup = ["General"];',
        ]
        for key, value in groups.get(d + ("General",), {}).items():
            out.append(f"  desk.writeConfig({js(key)}, {js(unescape(value))});")
        for g in sorted(groups):
            if len(g) == 4 and g[:2] == d and g[2] == "Applets":
                aid, plugin = g[3], groups[g].get("plugin")
                x, y, w, h = geometries.get(aid, (0, 0, 300, 300))
                var = f"d{aid}"
                out.append(f"  var {var} = desk.addWidget({js(plugin)}, {x}, {y}, {w}, {h});")
                out += ["  " + line for line in applet_config_lines(var, groups, g)]
        out.append("});")
    return "\n".join(out) + "\n"


def parse_geometries(text: str) -> dict[str, tuple[int, int, int, int]]:
    """'Applet-86:0,0,224,352,0;...' -> {'86': (0, 0, 224, 352)}."""
    result = {}
    for item in text.split(";"):
        m = re.match(r"Applet-(\d+):(-?\d+),(-?\d+),(\d+),(\d+)", item)
        if m:
            result[m.group(1)] = tuple(int(v) for v in m.groups()[1:])
    return result


def start_button_lines(var: str, groups, prefix, start_button: str) -> list[str]:
    if start_button == "kickoff":
        lines = [f'var {var} = panel.addWidget("org.kde.plasma.kickoff");']
        lines += applet_config_lines(var, groups, prefix)
        # The Mac look keeps a plain Kickoff button (SHOJI_START_ICON).
        lines += [f'{var}.currentConfigGroup = ["General"];', f'{var}.writeConfig("icon", {js(MAC_START_ICON)});']
        return lines
    orb = LNF_DIR / "org.shojiwm.aero.desktop/contents/orb/start-orb-vista-sheet.png"
    lines = [f'var {var} = panel.addWidget("io.gitgud.wackyideas.SevenStart");']
    shortcut = groups.get(prefix + ("Shortcuts",), {}).get("global")
    if shortcut:
        lines.append(f"{var}.globalShortcut = {js(shortcut)};")
    lines += [
        f'{var}.currentConfigGroup = ["General"];',
        f'{var}.writeConfig("useCustomButtonImage", true);',
        # Rest, hover and pressed frames, stacked top to bottom.
        f'{var}.writeConfig("customButtonImage", {js("file://" + str(orb))});',
        # Like Windows 7 the orb is taller than the panel and sticks out above
        # it, in its own small window (patched SevenStart, see patch-sevenstart.py).
        f'{var}.writeConfig("stickOutOrb", true);',
        f'{var}.writeConfig("orbWidth", {ORB_SIZE});',
    ]
    return lines


def kdeglobals(group: str, key: str, fallback: str) -> str:
    """A value from ~/.config/kdeglobals, so the looks keep your icons and style."""
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    try:
        parser.read(HOME / ".config/kdeglobals")
        return parser.get(group, key)
    except (configparser.Error, OSError):
        return fallback


ICON_THEME = kdeglobals("Icons", "Theme", "breeze-dark")
WIDGET_STYLE = kdeglobals("KDE", "widgetStyle", "Breeze")

DEFAULTS = {
    "mac": """[kdeglobals][KDE]
widgetStyle={style}

[kdeglobals][General]
ColorScheme=BreezeDark

[kdeglobals][Icons]
Theme={icons}

[plasmarc][Theme]
name=default

[Desktop][org.kde.plasma.desktop]
Containment=org.kde.desktopcontainment
""",
    "aero": """[kdeglobals][KDE]
widgetStyle={style}

[kdeglobals][General]
ColorScheme=ShojiWMAeroDark

[kdeglobals][Icons]
Theme={icons}

[plasmarc][Theme]
name=ShojiWM-Aero

[Desktop][org.kde.plasma.desktop]
Containment=org.kde.desktopcontainment
""",
}

NAMES = {
    "mac": ("ShojiWM Mac", "Dark Breeze panel, Kickoff, macOS traffic light title bars"),
    "aero": ("ShojiWM Aero", "Dark Aero glass panel (Seven-Black), glowing start orb, Aero title bars"),
}


def build(kind: str, groups) -> pathlib.Path:
    pid = f"org.shojiwm.{kind}.desktop"
    root = LNF_DIR / pid
    if root.exists():
        shutil.rmtree(root)
    (root / "contents/layouts").mkdir(parents=True)
    (root / "contents/previews").mkdir(parents=True)
    name, description = NAMES[kind]
    metadata = {
        "KPackageStructure": "Plasma/LookAndFeel",
        "KPlugin": {
            "Authors": [{"Name": "shojiwm-kde-config"}],
            "Category": "",
            "Description": description,
            "Id": pid,
            "License": "GPLv3",
            "Name": name,
            "Version": "1.0",
        },
        "X-Plasma-APIVersion": "2",
    }
    (root / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    (root / "contents/defaults").write_text(DEFAULTS[kind].format(icons=ICON_THEME, style=WIDGET_STYLE))
    start = "kickoff" if kind == "mac" else "sevenstart"
    (root / "contents/layouts/org.kde.plasma.desktop-layout.js").write_text(layout_script(groups, start))
    if kind == "aero":
        (root / "contents/orb").mkdir()
        shutil.copy(ORB_SHEET, root / "contents/orb/start-orb-vista-sheet.png")
    for preview in ("preview.png", "fullscreenpreview.jpg"):
        src = SETUP / f"assets/global-theme-previews/{kind}-{preview}"
        if src.exists():
            shutil.copy(src, root / "contents/previews" / preview)
    return root


def main() -> None:
    snapshot = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SNAPSHOT
    groups = parse_kconfig(snapshot)
    for kind in ("mac", "aero"):
        print("built", build(kind, groups))


if __name__ == "__main__":
    main()
